export const DICT = { ru, en };
let lang = 'ru';
try { lang = localStorage.getItem('mt_lang') || (navigator.language || 'ru').slice(0, 2); } catch {}
if (!DICT[lang]) lang = 'ru';

export const getLang = () => lang;
export function setLang(l) { lang = DICT[l] ? l : 'ru'; try { localStorage.setItem('mt_lang', lang); } catch {} document.documentElement.lang = lang; }
export function t(key, vars) {
  let s = DICT[lang][key] ?? DICT.ru[key] ?? key;
  if (vars && typeof s === 'string') for (const k in vars) s = s.replaceAll('{' + k + '}', vars[k]);
  return s;
}
