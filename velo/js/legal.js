  function hasConsent() {
    try { const c = JSON.parse(localStorage.getItem(CONSENT_KEY) || 'null'); return !!(c && c.version === VERSION); }
    catch { return false; }
  }

  function saveConsent() {
    try { localStorage.setItem(CONSENT_KEY, JSON.stringify({ version: VERSION, at: new Date().toISOString() })); } catch { /* приватный режим */ }
  }

  function openDoc(kind) {
    const d = DOCS[kind];
    const m = document.getElementById('legal-modal');
    document.getElementById('legal-title').textContent = d.title;
    document.getElementById('legal-body').innerHTML = d.html;
    m.hidden = false;
    document.getElementById('legal-body').scrollTop = 0;
  }

  function closeDoc() { document.getElementById('legal-modal').hidden = true; }

  /** Полное удаление данных: IndexedDB, localStorage, кэши, service worker. */
  async function wipeAll() {
    try { localStorage.clear(); } catch { /* ignore */ }
    try { sessionStorage.clear(); } catch { /* ignore */ }
    try { await new Promise(res => { const r = indexedDB.deleteDatabase('velo'); r.onsuccess = r.onerror = r.onblocked = () => res(); }); } catch { /* ignore */ }
    try { if (window.caches) for (const k of await caches.keys()) await caches.delete(k); } catch { /* ignore */ }
    try { if (navigator.serviceWorker) for (const r of await navigator.serviceWorker.getRegistrations()) await r.unregister(); } catch { /* ignore */ }
    location.reload();
  }

  /** Экран согласия при первом запуске. onAccept — запускает геолокацию. */
  function mountConsent({ onAccept }) {
    const el = document.getElementById('consent');
    if (hasConsent()) { onAccept(); return; }
    el.hidden = false;
    const box = document.getElementById('consent-check');
    const go = document.getElementById('consent-accept');
    box.addEventListener('change', () => { go.disabled = !box.checked; });
    go.addEventListener('click', () => {
      saveConsent();
      el.hidden = true;
      onAccept();
    });
    document.getElementById('consent-decline').addEventListener('click', () => {
      el.hidden = true;
      if (root.VeloApp) root.VeloApp.toast('Без согласия местоположение не используется: GPS, лобби и запись поездок отключены', 5000);
    });
  }

  function bindLinks() {
    document.querySelectorAll('[data-legal]').forEach(b => b.addEventListener('click', () => openDoc(b.dataset.legal)));
    document.getElementById('legal-close').addEventListener('click', closeDoc);
    document.getElementById('legal-modal').addEventListener('click', e => { if (e.target.id === 'legal-modal') closeDoc(); });
    document.querySelectorAll('[data-wipe]').forEach(b => b.addEventListener('click', () => {
      if (confirm('Удалить все данные приложения на этом устройстве (поездки, маршруты, настройки, согласие) и выйти из лобби?')) wipeAll();
    }));
  }

  document.addEventListener('DOMContentLoaded', bindLinks);

